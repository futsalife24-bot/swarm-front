export const pixelImpactTextures = frames.map((frame) => {
  const bytes = new Uint8Array(16 * 16 * 4);
  frame.forEach((row, y) => {
    for (let x = 0; x < 16; x++) {
      const index = Number(row[x]);
      if (!index) continue;
      const color = palette[index];
      const i = (y * 16 + x) * 4;
      bytes[i] = color >> 16;
      bytes[i + 1] = (color >> 8) & 255;
      bytes[i + 2] = color & 255;
      bytes[i + 3] = 255;
    }
  });
  const texture = new T.DataTexture(bytes, 16, 16, T.RGBAFormat);
  texture.colorSpace = T.SRGBColorSpace;
  texture.magFilter = texture.minFilter = T.NearestFilter;
  texture.generateMipmaps = false;
  texture.needsUpdate = true;
  return texture;
});
