import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { createHash } from 'node:crypto';

// CC0の実録から短い開蓋部分だけを加工。原本と由来は assets/audio/supply/README.md。
const source='assets/audio/supply/0191-lock-source.ogg';
const scratch='dist-validation/crate-se';
mkdirSync(scratch,{recursive:true});
const cuts=[{start:1.28,duration:0.43},{start:1.30,duration:0.41}];
const pcm=cuts.map(({start,duration},i)=>{
  const path=`${scratch}/crate-${i}.pcm`;
  execFileSync('ffmpeg',['-hide_banner','-loglevel','error','-i',source,'-af',
    `atrim=start=${start}:duration=${duration},asetpts=PTS-STARTPTS,highpass=f=150,lowpass=f=6500,afade=t=in:d=0.002,afade=t=out:st=${duration-0.04}:d=0.04,acompressor=threshold=0.15:ratio=3:attack=1:release=35:makeup=1.4,volume=0.8`,
    '-ac','1','-ar','22050','-f','s16le','-y',path]);
  return readFileSync(path).toString('base64');
});
// 同期PCMなので初回の開封やWorker経路でも読込み待ちで音が欠けない。
const code=`// Generated by scripts/build-supply-crate-sample.mjs. Do not edit PCM by hand.
// Lock #0191, Joseph SARDIN / BigSoundBank, CC0.
// https://bigsoundbank.com/lock-s0191.html
const PCM = ${JSON.stringify(pcm)};
export function crateOpen(index = 0, targetRate = 44100) {
  const raw = atob(PCM[index]);
  const count = raw.length / 2, mono = new Float32Array(count);
  for (let i = 0; i < count; i++) {
    let value = raw.charCodeAt(i * 2) | raw.charCodeAt(i * 2 + 1) << 8;
    if (value >= 32768) value -= 65536;
    mono[i] = value / 32768;
  }
  const length = Math.ceil(count * targetRate / 22050);
  const left = new Float32Array(length), right = new Float32Array(length);
  for (let i = 0; i < length; i++) {
    const x = i * 22050 / targetRate, j = Math.floor(x), f = x - j;
    left[i] = right[i] = (mono[j] + ((mono[j + 1] ?? mono[j]) - mono[j]) * f) * Math.SQRT1_2;
  }
  return [left, right];
}
`;
writeFileSync('public/supply-reveal/crate-open-pcm.js',code);
writeFileSync(`${scratch}/sample-build.json`,JSON.stringify({source,sourceSha256:createHash('sha256').update(readFileSync(source)).digest('hex'),sampleRate:22050,cuts,bytes:code.length},null,2));
console.log(JSON.stringify({clips:cuts.length,moduleBytes:code.length}));
